import React, { useState } from 'react';
import { Link, useNavigate } from 'react-router-dom';
import { useForm } from 'react-hook-form';
import { zodResolver } from '@hookform/resolvers/zod';
import { z } from 'zod';
import { LockIcon, MailIcon } from 'lucide-react';
import { Button } from '../../components/ui/Button';
import { Checkbox, Input } from '../../components/ui/Input';
import { Alert } from '../../components/ui/Feedback';
import { authService } from '../../services/authService';
import { useApp } from '../../contexts/AppContext';
import { demoCredentials } from '../../data/mockUsers';

const schema = z.object({
  email: z.string().min(1, 'Email is required').email('Enter a valid email address'),
  password: z.string().min(6, 'Password must be at least 6 characters'),
  remember: z.boolean()
});

type FormValues = z.infer<typeof schema>;

export function Login() {
  const navigate = useNavigate();
  const { signIn } = useApp();
  const [error, setError] = useState<string | null>(null);

  const {
    register,
    handleSubmit,
    setValue,
    clearErrors,
    formState: { errors, isSubmitting }
  } = useForm<FormValues>({
    resolver: zodResolver(schema),
    defaultValues: { email: '', password: '', remember: true }
  });

  const onSubmit = async (values: FormValues) => {
    setError(null);
    try {
      const user = await authService.login(values);
      signIn(user);
      navigate('/dashboard', { replace: true });
    } catch {
      setError('Sign-in failed against the mock service. Please try again.');
    }
  };

  const fillDemo = (role: keyof typeof demoCredentials) => {
    setError(null);
    setValue('email', demoCredentials[role].email, { shouldDirty: true, shouldTouch: true, shouldValidate: true });
    setValue('password', demoCredentials[role].password, { shouldDirty: true, shouldTouch: true, shouldValidate: true });
    clearErrors(['email', 'password']);
  };

  return (
    <div>
      <h1 className="text-[26px] font-bold tracking-tight text-leaf-900">Sign in</h1>
      <p className="mt-1.5 text-sm leading-6 text-earth-600">
        Access the AgriGuard AI Advisory Platform. Predictions in this build are generated by mock services for demonstration.
      </p>

      {error &&
      <Alert variant="danger" className="mt-5">
          {error}
        </Alert>
      }

      <form className="mt-6 space-y-4" onSubmit={handleSubmit(onSubmit)} noValidate>
        <Input
          label="Email"
          type="email"
          autoComplete="email"
          placeholder="you@example.lk"
          required
          icon={<MailIcon className="h-4 w-4" aria-hidden="true" />}
          error={errors.email?.message}
          {...register('email')} />
        
        <Input
          label="Password"
          type="password"
          autoComplete="current-password"
          placeholder="••••••••"
          required
          icon={<LockIcon className="h-4 w-4" aria-hidden="true" />}
          error={errors.password?.message}
          {...register('password')} />
        

        <div className="flex items-center justify-between gap-3">
          <Checkbox label="Remember me" {...register('remember')} />
          <Link to="/forgot-password" className="text-[13px] font-semibold text-leaf-700 hover:text-leaf-900">
            Forgot password?
          </Link>
        </div>

        <Button type="submit" size="lg" fullWidth loading={isSubmitting}>
          Sign In
        </Button>
      </form>

      <div className="mt-4 rounded-lg border border-dashed border-earth-300 bg-earth-50 p-3 text-[12px] leading-5 text-earth-700">
        <p>
          <span className="font-semibold text-leaf-900">Demo credentials</span> - choose a role to fill the form.
        </p>
        <div className="mt-2 grid gap-2 sm:grid-cols-2">
          <button
            type="button"
            onClick={() => fillDemo('user')}
            className="rounded-md border border-earth-200 bg-white px-3 py-2 text-left transition-colors duration-150 ease-out hover:border-leaf-300 hover:bg-leaf-50">
            <span className="block font-semibold text-leaf-900">User side</span>
            <span className="block truncate">{demoCredentials.user.email}</span>
            <span className="block font-mono text-[11px]">{demoCredentials.user.password}</span>
          </button>
          <button
            type="button"
            onClick={() => fillDemo('admin')}
            className="rounded-md border border-earth-200 bg-white px-3 py-2 text-left transition-colors duration-150 ease-out hover:border-leaf-300 hover:bg-leaf-50">
            <span className="block font-semibold text-leaf-900">Admin side</span>
            <span className="block truncate">{demoCredentials.admin.email}</span>
            <span className="block font-mono text-[11px]">{demoCredentials.admin.password}</span>
          </button>
        </div>
      </div>

      <p className="mt-6 text-[13px] text-earth-600">
        First time here?{' '}
        <Link to="/register" className="font-semibold text-leaf-700 hover:text-leaf-900">
          Create an account
        </Link>
      </p>
    </div>);

}
